import type { LearningWord } from "@/lib/learning-types"

function word(
  id: string,
  arabic: string,
  transliteration: string,
  meaning: string,
  pools: string[],
  extra: Partial<LearningWord> = {},
): LearningWord {
  return {
    id,
    arabic,
    transliteration,
    meaning,
    kind: extra.kind ?? "word",
    domains: extra.domains ?? pools.map((pool) => pool.split(".")[0] ?? pool),
    pools,
    difficulty: extra.difficulty ?? 1,
    register: extra.register ?? "shared",
    notes: extra.notes,
  }
}

