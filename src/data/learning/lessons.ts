export function getLesson(id: string) {
  return lessons.find((item) => item.id === id)
}

export function unlockedLessons(completedMissionIds: string[], completedLessonIds: string[]) {
  return lessons.filter(
    (lesson) =>
      lesson.unlockAfterMissionIds.some((id) => completedMissionIds.includes(id)) &&
      !completedLessonIds.includes(lesson.id),
  )
}
