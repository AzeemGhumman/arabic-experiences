function enrichVocab(item: VocabularyItem): VocabularyItem {
  const lex = getLexiconBySceneId(item.id)
  if (!lex) {
    return { ...item, quranFrequency: undefined }
  }

  return {
    ...item,
    arabic: lex.arabic || item.arabic,
    ipa: lex.ipa ?? undefined,
    quranFrequency: lex.quranFrequency ?? undefined,
    quranPos: lex.quranPos ?? undefined,
    quranLemma: lex.quranLemma ?? undefined,
    msaRank: lex.msaRank ?? undefined,
    msaGloss: lex.msaGloss ?? undefined,
    phrases: lex.phrases.length > 0 ? lex.phrases : undefined,
    swadeshNo: lex.swadeshNo ?? undefined,
  }
}

export function getVocab(id: string) {
  const item = vocabulary.find((entry) => entry.id === id)
  return item ? enrichVocab(item) : undefined
}

export function getVocabByIds(ids: string[]) {
  return ids.map((id) => getVocab(id)).filter((item): item is VocabularyItem => Boolean(item))
}

